public class Char {
    public static void main(String[] args) {

        char inicialDoNome = 'K';
        char tipoCliente = '2';
        char simbolo = '@';

        System.out.println("Inicial do nome: " + inicialDoNome);
        System.out.println("Tipo do cliente: " + tipoCliente);
        System.out.println("Tipo do simbolo: " + simbolo);
    }
}
