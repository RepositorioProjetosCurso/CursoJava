public class Long {
    public static void main(String[] args) {

//      É utilizado o L no final da variável para definir que é do tipo long.
        long populacaoFortaleza = 2_500_000L;
        long populacaoAmericaLatina = 2_147_483_648L;

        System.out.println("populacaoFortaleza = " + populacaoFortaleza);
        System.out.println("populacaoAmericaLatina = " + populacaoAmericaLatina);
    }
}
