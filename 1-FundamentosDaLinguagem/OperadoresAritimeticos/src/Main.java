public class Main {
    public static void main(String[] args) {

        int minhaIdade= 22;
        int suaIdade = 26;

        // Adição
        int totalIdades = minhaIdade + suaIdade;
        System.out.println("Total idades: " + totalIdades);

        // Subtração
        int diferencaIdades = minhaIdade - suaIdade;
        System.out.println("Diferenca: " + diferencaIdades);

        // Multiplicação
        int dobroDaIdade = 2 * suaIdade;
        System.out.println("Dobro da sua idade: " + dobroDaIdade);

        // Divisão
        int metadeDaIdade = suaIdade / 2;
        System.out.println("Metade da sua idade: " + metadeDaIdade);

        // Módulo
        int restoDaDivisao = 7 % 2;
        System.out.println("Resto da divisão (módulo): " + restoDaDivisao);
    }
}
